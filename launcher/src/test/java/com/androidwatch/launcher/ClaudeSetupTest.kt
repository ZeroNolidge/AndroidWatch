package com.androidwatch.launcher

import com.androidwatch.launcher.claude.ClaudeInbox
import com.androidwatch.launcher.claude.ClaudeProject
import org.json.JSONObject
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Test

class ClaudeSetupTest {
    @Test fun parsesPhoneSetupCode() {
        val p = ClaudeProject.fromJson(
            JSONObject("""{"v":1,"name":"Watch","routine":"trig_01ABC","token":"sk-ant-oat01-x","inbox":"https://github.com/Owner/Repo/issues/12"}"""),
        )
        assertEquals("Owner", p.owner)
        assertEquals("Repo", p.repo)
        assertEquals(12, p.issue)
        assertEquals("trig_01ABC", p.routineId)
        assertNull(p.githubToken)
    }

    @Test(expected = IllegalArgumentException::class)
    fun rejectsNonRoutineId() {
        ClaudeProject.fromJson(JSONObject("""{"routine":"abc","token":"t","inbox":"https://github.com/o/r/issues/1"}"""))
    }

    @Test fun stripsClaudeCodeFooter() {
        val body = "✅ Done: fixed the build.\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"
        assertEquals("✅ Done: fixed the build.", ClaudeInbox.cleanBody(body))
    }

    @Test fun keepsHorizontalRulesThatAreNotTheFooter() {
        val body = "Part one\n---\nPart two"
        assertEquals(body, ClaudeInbox.cleanBody(body))
    }
}
